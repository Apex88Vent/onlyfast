CREATE OR REPLACE FUNCTION public.onlylaps_sector_track_revision()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if TG_OP = 'UPDATE' and (to_jsonb(new) - 'updated_at') = (to_jsonb(old) - 'updated_at') then
    return null;
  end if;
  -- RLS still authorizes the initiating sector write. This trigger can only
  -- invalidate the parent revision, including a driver's personal layout.
  if TG_OP <> 'INSERT' then
    update public.onlylaps_track_maps set version = coalesce(version,1)+1 where id = old.track_id;
  end if;
  if TG_OP = 'INSERT' or (TG_OP = 'UPDATE' and new.track_id is distinct from old.track_id) then
    update public.onlylaps_track_maps set version = coalesce(version,1)+1 where id = new.track_id;
  end if;
  return null;
end $function$
;
revoke all on function public."onlylaps_sector_track_revision"() from public, anon, authenticated;
CREATE OR REPLACE FUNCTION public.onlylaps_track_revision_on_update()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  -- Ignore timestamp-only updates, but never accept a stale client version.
  if (to_jsonb(new) - 'updated_at') is distinct from (to_jsonb(old) - 'updated_at') then
    new.version := coalesce(old.version, 1) + 1;
  end if;
  return new;
end $function$
;
revoke all on function public."onlylaps_track_revision_on_update"() from public, anon, authenticated;
